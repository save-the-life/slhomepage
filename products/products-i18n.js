(function(){
  var I18N = window.SL_PRODUCTS_I18N || {};
  var page = document.documentElement.getAttribute('data-page') || '';
  var els = document.querySelectorAll('[data-i18n]');
  var defaults = new WeakMap();
  Array.prototype.forEach.call(els, function(el){ defaults.set(el, el.innerHTML); });
  var enTitle = document.title;
  var descEl = document.querySelector('meta[name="description"]');
  var enDesc = descEl ? descEl.getAttribute('content') : '';

  function apply(lang){
    var pack = I18N[lang];
    if(!pack) lang = 'en';
    document.documentElement.lang = pack ? pack.htmlLang : 'en';
    Array.prototype.forEach.call(els, function(el){
      var k = el.getAttribute('data-i18n');
      if(pack && pack.t[k] != null){ el.innerHTML = pack.t[k]; }
      else { el.innerHTML = defaults.get(el); }
    });
    var meta = pack && pack.pages ? pack.pages[page] : null;
    document.title = meta ? meta[0] : enTitle;
    if(descEl) descEl.setAttribute('content', meta ? meta[1] : enDesc);
    Array.prototype.forEach.call(document.querySelectorAll('.lang-sel'), function(s){ s.value = lang; });
    try{ localStorage.setItem('sl-lang', lang); }catch(e){}
  }

  Array.prototype.forEach.call(document.querySelectorAll('.lang-sel'), function(s){
    s.addEventListener('change', function(){ apply(s.value); });
  });

  var saved = null; try{ saved = localStorage.getItem('sl-lang'); }catch(e){}
  var urlLang = new URLSearchParams(location.search).get('lang');
  var init = urlLang || saved || 'en';
  if(init !== 'en') apply(init);
})();
